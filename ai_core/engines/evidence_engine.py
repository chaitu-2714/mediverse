"""
MediVerse AI — Evidence Engine.
Verifies AI responses against retrieved context and formatting citations.
"""
from __future__ import annotations

import logging
from typing import Optional

from core.models.search_result import AIResponse, SourceReference
from core.exceptions import NoEvidenceFoundError

logger = logging.getLogger("mediverse.ai.evidence")


class EvidenceEngine:
    """
    Ensures that LLM responses are backed by evidence from the
    knowledge repository. Formats citations for UI display.
    """

    def __init__(self) -> None:
        pass

    def verify_response(self, response: AIResponse) -> AIResponse:
        """
        Verify the AI response against its sources.
        Can be used to check if the LLM hallucinated, though the current
        system prompt is designed to prevent this.
        Returns the (potentially modified) response.
        """
        if not response.has_evidence or not response.sources:
            return response

        # Check if the LLM admitted it couldn't find the answer
        no_answer_phrases = [
            "does not contain sufficient information",
            "cannot answer",
            "I don't know",
            "not mentioned in the provided context",
        ]

        text = response.answer.lower()
        if any(phrase in text for phrase in no_answer_phrases):
            logger.info("LLM admitted lack of evidence in generated text.")
            # We still keep the sources to show what was retrieved,
            # but we might lower the confidence score.
            response.confidence = min(response.confidence, 0.3)

        return response

    def format_citations_markdown(self, response: AIResponse) -> str:
        """
        Format the response and its sources into a comprehensive
        Markdown document.
        """
        if not response.has_evidence:
            return f"### AI Response\n\n{response.answer}\n"

        parts = [
            f"### AI Response\n\n{response.answer}\n\n",
            "---\n\n",
            "### Supporting Evidence\n\n",
        ]

        # Group sources by document
        doc_sources: dict[str, list[SourceReference]] = {}
        for src in response.sources:
            if src.document_title not in doc_sources:
                doc_sources[src.document_title] = []
            doc_sources[src.document_title].append(src)

        for title, sources in doc_sources.items():
            parts.append(f"#### 📄 {title}\n")
            for src in sources:
                parts.append(
                    f"- **Page {src.page_number}** (Relevance: {src.score_pct}%)\n"
                    f"  > _{src.chunk_text}_...\n"
                )
            parts.append("\n")

        parts.append(
            f"---\n*Response generated by {response.model_used} "
            f"in {response.processing_time_ms}ms with "
            f"{response.confidence_label} ({response.confidence_pct}%)*"
        )

        return "".join(parts)

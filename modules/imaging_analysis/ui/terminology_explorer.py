    def __init__(self, parent=None) -> None:
        super().__init__(parent)
        self._ai = get_ai_engine()
        self.setFixedWidth(300)
        self.setStyleSheet("""
            QFrame {
                background: rgba(15, 23, 42, 0.95);
                border-left: 1px solid rgba(255, 255, 255, 0.08);
            }
        """)

        layout = QVBoxLayout(self)
        layout.setContentsMargins(15, 15, 15, 15)
        layout.setSpacing(15)

        # Header bar
        hdr = QHBoxLayout()
        self.title_lbl = QLabel("Terminology Explorer")
        self.title_lbl.setStyleSheet("color: white; font-size: 13.5px; font-weight: bold; border: none; background: transparent;")
        hdr.addWidget(self.title_lbl, 1)

        self.btn_close = QPushButton("✕")
        self.btn_close.setFixedSize(24, 24)
        self.btn_close.setCursor(Qt.PointingHandCursor)
        self.btn_close.setStyleSheet("""
            QPushButton { background: rgba(255,255,255,0.05); color: white; border: none; border-radius: 4px; }
            QPushButton:hover { background: rgba(239,68,68,0.2); }
        """)
        self.btn_close.clicked.connect(self.close_requested.emit)
        hdr.addWidget(self.btn_close)
        layout.addLayout(hdr)

        # Scrollable content area
        self.scroll = QScrollArea()
        self.scroll.setWidgetResizable(True)
        self.scroll.setStyleSheet("QScrollArea { border: none; background: transparent; }")
        
        self.container = QWidget()
        self.container.setStyleSheet("background: transparent;")
        self.content_layout = QVBoxLayout(self.container)
        self.content_layout.setContentsMargins(0, 0, 0, 0)
        self.content_layout.setSpacing(15)
        self.content_layout.setAlignment(Qt.AlignTop)
        
        self.scroll.setWidget(self.container)
        layout.addWidget(self.scroll, 1)

        # Pre-set blank state
        self._set_placeholder()

    def _set_placeholder(self) -> None:
        self.title_lbl.setText("Terminology Explorer")
        lbl = QLabel("Click any highlighted blue medical term link in the report summary to inspect its clinical definition and evidence guidelines.")
        lbl.setWordWrap(True)
        lbl.setStyleSheet("color: rgba(255,255,255,0.4); font-size: 12px; line-height: 1.5; border: none;")
        self.content_layout.addWidget(lbl)

    def _clear_content(self) -> None:
        while self.content_layout.count():
            item = self.content_layout.takeAt(0)
            if item.widget():
                item.widget().deleteLater()

    def inspect_term(self, term: str) -> None:
        """Inspects the clinical term using pre-seeded dictionary + RAG database fallback."""
        self._clear_content()
        self.title_lbl.setText(f"Inspect: {term}")

        term_key = term.lower().strip()
        # Find dictionary info
        info = self.CLINICAL_DICTIONARY.get(term_key)
        
        # Fallback default info
        if not info:
            info = {
                "definition": f"Clinical parameter or finding associated with diagnostic procedures.",
                "anatomy": "Systemic Soft Tissue Nodes",
                "purpose": "Standard clinical diagnostics mapping.",
                "context": f"Levels are evaluated relative to patient age, clinical indicators, and other test coordinates."
            }

        # 1. Add Definition Block
        self._add_card("📜 CLINICAL DEFINITION", info["definition"])
        
        # 2. Add Related Anatomy
        self._add_card("🫁 ASSOCIATED ANATOMY", info["anatomy"])

        # 3. Add Diagnostic Purpose
        self._add_card("🔬 CLINICAL PURPOSE", info["purpose"])

        # 4. Add Common Clinical Context
        self._add_card("💡 CLINICAL CONTEXT", info["context"])

        # 5. Retrieve RAG evidence citations
        self._load_rag_evidence(term)

    def _add_card(self, title: str, text: str) -> None:
        card = QFrame()
        card.setStyleSheet("background: rgba(255,255,255,0.03); border: 1px solid rgba(255,255,255,0.05); border-radius: 8px;")
        l = QVBoxLayout(card)
        l.setSpacing(6)
        l.setContentsMargins(10, 10, 10, 10)
        
        t_lbl = QLabel(title)
        t_lbl.setStyleSheet("color: #06b6d4; font-size: 9px; font-weight: bold; border: none;")
        l.addWidget(t_lbl)
        
        c_lbl = QLabel(text)
        c_lbl.setWordWrap(True)
        c_lbl.setStyleSheet("color: rgba(255,255,255,0.85); font-size: 11.5px; line-height: 1.4; border: none;")
        l.addWidget(c_lbl)
        
        self.content_layout.addWidget(card)

    def _load_rag_evidence(self, term: str) -> None:
        # Search RAG
        try:
            logger.info(f"Querying RAG for terminology: '{term}'")
            results = self._ai.search_only(term, top_k=2)
            
            if results:
                card = QFrame()
                card.setStyleSheet("background: rgba(16,185,129,0.02); border: 1px solid rgba(16,185,129,0.1); border-radius: 8px;")
                l = QVBoxLayout(card)
                l.setSpacing(6)
                l.setContentsMargins(10, 10, 10, 10)

                t_lbl = QLabel("📚 GUIDELINES EVIDENCE")
                t_lbl.setStyleSheet("color: #10b981; font-size: 9px; font-weight: bold; border: none;")
                l.addWidget(t_lbl)

                for r in results:
                    r_lbl = QLabel(f"[{r.category.upper()}] {r.document_title}\n\"{r.preview[:120]}...\"")
                    r_lbl.setWordWrap(True)
                    r_lbl.setStyleSheet("color: rgba(255,255,255,0.7); font-size: 10.5px; border: none; padding-top: 4px;")
                    l.addWidget(r_lbl)
                self.content_layout.addWidget(card)
        except Exception as e:
            logger.warning(f"Failed to load RAG guidelines in terminology: {e}")
